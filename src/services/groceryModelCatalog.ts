/**
 * Normalizes class name (e.g. 'Golden-Delicious' -> 'golden-delicious')
 */
export function normalizeClassKey(raw: string): string {
  return (raw || '').toLowerCase().replace(/[_\s]+/g, '-').trim();
}

/**
 * Finds catalog item for a given predicted class or label
 */
export function findCatalogItemByClass(rawClass: string): GroceryCatalogItem | null {
  const norm = normalizeClassKey(rawClass);
  if (GROCERY_CATALOG[norm]) return GROCERY_CATALOG[norm];

  // Fallback search by partial word match
  for (const [key, item] of Object.entries(GROCERY_CATALOG)) {
    if (norm.includes(key) || key.includes(norm)) return item;
    if (item.nameEn.toLowerCase().includes(norm) || item.nameFr.toLowerCase().includes(norm)) return item;
  }
  return null;
}

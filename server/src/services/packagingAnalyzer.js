/**
 * Multi-item analyzer:
 * Parses multiple items from flyer circular pages, grocery receipts, or countertop hauls
 */
export function analyzeMultiItemPackagingText(rawText, preferredLanguage = "FR") {
  const lang = (preferredLanguage || "FR").toUpperCase().startsWith("FR") ? "FR" : "EN";
  if (!rawText || typeof rawText !== "string") return [];

  const foundItems = [];
  const seenNames = new Set();

  // First pass: scan the full catalog for matches in the whole text block
  for (const catalogItem of QUEBEC_GROCERY_CATALOG) {
    for (const kw of catalogItem.keywords) {
      if (rawText.toLowerCase().includes(kw)) {
        const itemKey = catalogItem.nameFr;
        if (!seenNames.has(itemKey)) {
          seenNames.add(itemKey);
          const singleInsight = analyzePackagingText(kw, lang);
          if (singleInsight) foundItems.push(singleInsight);
          break;
        }
      }
    }
  }

  // If catalog scan found items, return them
  if (foundItems.length > 0) {
    return foundItems;
  }

  // Check PLU produce codes
  const pluMatch = rawText.match(/\b([34]\d{3})\b/);
  if (pluMatch && PLU_PRODUCE_MAP[pluMatch[1]]) {
    const singleInsight = analyzePackagingText(pluMatch[1], lang);
    if (singleInsight) return [singleInsight];
  }

  // Second pass: line-by-line fallback with strict noise filtering
  const lines = rawText.split(/\r?\n/).map((l) => l.trim()).filter((l) => l.replace(/[^a-zA-ZÀ-ÿ]/g, "").length >= 3);
  for (const line of lines) {
    const insight = analyzePackagingText(line, lang);
    if (insight && insight.name && insight.name.replace(/[^a-zA-ZÀ-ÿ]/g, "").length >= 3) {
      if (!seenNames.has(insight.name)) {
        seenNames.add(insight.name);
        foundItems.push(insight);
      }
    }
    if (foundItems.length >= 10) break;
  }

  return foundItems;
}
